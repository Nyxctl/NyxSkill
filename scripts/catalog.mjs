import { resolve } from 'node:path';
import { writeFile } from 'node:fs/promises';
import { loadRegistry } from '../dist/src/registry.js';
const registry=await loadRegistry(resolve('.'));
await writeFile('docs/SKILLS-CATALOG.md', '# Canonical skills\n\nGenerated by `node scripts/catalog.mjs`.\n\n| ID | Description |\n| --- | --- |\n'+registry.skills.map(s=>`| ${s.meta.id} | ${s.meta.description.replaceAll('|','/')} |`).join('\n')+'\n');
await writeFile('docs/PACKS-CATALOG.md', '# Canonical packs\n\nGenerated from pack metadata.\n\n| ID | Version | Skills |\n| --- | --- | --- |\n'+registry.packs.map(p=>`| ${p.id} | ${p.version} | ${p.skills.length} |`).join('\n')+'\n');
